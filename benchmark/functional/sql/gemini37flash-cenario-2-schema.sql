CREATE TABLE accounts (
  id BIGINT PRIMARY KEY, holder TEXT NOT NULL, balance_cents BIGINT NOT NULL CHECK (balance_cents >= 0),
  status TEXT NOT NULL CHECK (status IN ('ACTIVE','INACTIVE','BLOCKED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE transfers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_account_id BIGINT NOT NULL REFERENCES accounts(id), to_account_id BIGINT NOT NULL REFERENCES accounts(id),
  amount_cents BIGINT NOT NULL CHECK (amount_cents > 0), status TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), CHECK (from_account_id <> to_account_id)
);
